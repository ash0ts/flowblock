import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { compilePlan } from "../../../src/domain";
import { checkerVersion, gradePlan, type Task } from "./grade";
import { actionSchema } from "./planner";
import { sha256 } from "./fixtures";

const directory = resolve(process.argv[2]);
const taskBytes = await readFile(resolve(directory, "tasks.json"));
const sourceBytes = await readFile(resolve(directory, "actions.jsonl"));
const labelBytes = await readFile(resolve(directory, "labels.json"));
const tasks = new Map(
  (JSON.parse(taskBytes.toString()) as Task[]).map((task) => [task.id, task]),
);
const rows = sourceBytes
  .toString()
  .trim()
  .split("\n")
  .map((line) => JSON.parse(line));
const labels = JSON.parse(labelBytes.toString()) as {
  taskId: string;
  type: string;
  target: string;
}[];
if (rows.length !== labels.length)
  throw new Error("Training label/row cardinality differs.");
let positiveCompiles = 0,
  positiveFinishes = 0,
  checkedConstraintFinishes = 0;
for (const [index, row] of rows.entries()) {
  const label = labels[index];
  const task = tasks.get(label.taskId);
  if (!task) throw new Error("Teacher label has no source task.");
  const target = actionSchema.parse(JSON.parse(row.messages.at(-1).content));
  if (
    target.action === "compile_candidate" &&
    label.type !== "checked-constraint-initial"
  ) {
    const plan = compilePlan(
      task.input.scene,
      task.input.gear,
      task.input.intent,
      target.recipeId,
      target.overrides,
    );
    if (!gradePlan(task, plan).productive)
      throw new Error(
        `Positive compile fails ${checkerVersion}: ${label.taskId}`,
      );
    positiveCompiles++;
  }
  if (target.action === "finish") {
    const compiles = row.messages
      .slice(0, -1)
      .filter((message: { role: string }) => message.role === "assistant")
      .map((message: { content: string }) =>
        actionSchema.parse(JSON.parse(message.content)),
      )
      .filter(
        (action: { action: string }) => action.action === "compile_candidate",
      );
    if (!compiles.length)
      throw new Error("Finish has no actual compile context.");
    const plans = compiles.map(
      (action: {
        recipeId: Parameters<typeof compilePlan>[3];
        overrides?: Parameters<typeof compilePlan>[4];
      }) =>
        compilePlan(
          task.input.scene,
          task.input.gear,
          task.input.intent,
          action.recipeId,
          action.overrides,
        ),
    );
    for (const id of target.candidateIds) {
      const plan = plans.find(
        (candidate: { id: string }) => candidate.id === id,
      );
      if (!plan || !gradePlan(task, plan).productive)
        throw new Error(
          `Positive finish fails ${checkerVersion}: ${label.taskId}`,
        );
    }
    if (target.candidateIds.length) positiveFinishes++;
    else checkedConstraintFinishes++;
  }
}
const result = {
  schemaVersion: 1,
  checkerVersion,
  checkedAt: new Date().toISOString(),
  sourceHashes: {
    tasks: sha256(taskBytes),
    actions: sha256(sourceBytes),
    labels: sha256(labelBytes),
    checker: sha256(await readFile("training/experiments/next/grade.ts")),
  },
  rows: rows.length,
  positiveCompiles,
  positiveFinishes,
  checkedConstraintFinishes,
  status: "passed",
  limitations: [
    "Automated replay against explicit brief constraints; not attributed human cinematography review.",
    "The frozen dataset was generated by v3. V4 removes an undisclosed five-percent apparent-size threshold; source examples are unchanged.",
  ],
};
const path = resolve(directory, "semantic-audit-v4.json");
await writeFile(path, JSON.stringify(result, null, 2) + "\n", { flag: "wx" });
console.log(JSON.stringify(result));
